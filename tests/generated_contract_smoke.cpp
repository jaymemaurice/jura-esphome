#include "components/jura/jura.h"
using namespace esphome;
int main() {
  jura::JuraComponent machine;
  machine.set_named_command(jura::JuraButtonType::POWER_ON, "AN:01", 1, 1000);
  machine.set_named_command(jura::JuraButtonType::LATTE_MACCHIATO, "FA:06", 1, 1000);
  machine.set_named_command(jura::JuraButtonType::MILK_FROTH, "FA:08", 1, 1000);
  machine.set_named_command(jura::JuraButtonType::STEAM, "FA:09", 1, 1000);
  machine.set_named_command(jura::JuraButtonType::RINSE, "FA:0B", 1, 1000);
  machine.set_ram_probe_interval_seconds(30.0f);
  machine.set_ram_probe_interval_seconds(0.0f);
  machine.set_power_poll_interval(30000);
  machine.set_ready_poll_interval(5000);
  machine.set_eeprom_probe_interval_seconds(30.0f);
  machine.set_eeprom_probe_interval_seconds(0.0f);
  (void) machine.request_power(true);
  (void) machine.request_power(false);
  (void) machine.queue_raw_command("AN:20");
  machine.set_tx_floating(true);
  (void) machine.is_tx_floating();
  machine.set_tx_floating(false);
  machine.set_automatic_traffic_enabled(false);
  (void) machine.is_automatic_traffic_enabled();
  (void) machine.start_tx_hold(true, 250);
  (void) machine.start_tx_hold(false, 250);
  (void) machine.start_uart_break(20, 20);
  (void) machine.send_uart_break_13bit();
  (void) machine.is_tx_line_override_active();
  machine.set_automatic_traffic_enabled(true);
  (void) machine.start_guided_debug(false, 2, "");
  machine.cancel_guided_debug();
  (void) machine.start_grinder_mapping(2);
  (void) machine.start_menu_mapping(1);
  (void) machine.start_full_menu_ram_discovery(1);
  (void) machine.start_menu_ram_discovery_section("Product: Water");
  (void) machine.continue_debug_operation();
  (void) machine.start_discovery(jura::JuraButtonType::RAM_DUMP);
  (void) machine.start_discovery(jura::JuraButtonType::EEPROM_DUMP);
  machine.cancel_active_operation();
  (void) machine.start_brew_batch("Coffee", 2, "Default");
  machine.cancel_active_operation();
  machine.set_eeprom_discovery(0x00, 0xF0, 0x10, 2);
  machine.set_ram_discovery(0x00, 0xF0, 0x10, 2);
  sensor::Sensor timer_d0;
  sensor::Sensor timer_f0;
  sensor::Sensor timer_fc;
  sensor::Sensor awake;
  sensor::Sensor eeprom00;
  sensor::Sensor press_total;
  machine.set_ram_d0_d1_sensor(&timer_d0);
  machine.set_ram_f0_f1_sensor(&timer_f0);
  machine.set_ram_fc_fd_sensor(&timer_fc);
  machine.set_candidate_awake_consensus_sensor(&awake);
  machine.set_eeprom_00_sensor(&eeprom00);
  machine.set_button_press_total_sensor(&press_total);
  jura::JuraCounterNumber user_steam(&machine, 0xCB);
  machine.register_user_counter_number(0xCB, &user_steam);
  jura::JuraRecipeNumber coffee_water(&machine, jura::JuraRecipeParameter::COFFEE_WATER);
  machine.register_recipe_number(jura::JuraRecipeParameter::COFFEE_WATER, &coffee_water);
  machine.set_recipe_writes_enabled(false);
  (void) machine.are_recipe_writes_enabled();
  jura::JuraPowerSwitch power_switch(&machine);
  machine.register_power_switch(&power_switch);
  jura::JuraButton power(&machine, jura::JuraButtonType::POWER_ON);
  jura::JuraButton eeprom(&machine, jura::JuraButtonType::EEPROM_DUMP);
  (void) power;
  (void) eeprom;
  return 0;
}
